import {mkdir, readFile, writeFile} from "node:fs/promises";
import {dirname, relative, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const project = fileURLToPath(new URL("./", import.meta.url));
const scene = resolve(project, "level.aml");
const destination = resolve("generated/kowloon-circulation/stair-study/tiled.aml");
const start = "  <!-- Lower stair finish details (generated by update-stair-study.mjs). -->";
const end = "  <!-- End lower stair finish details. -->";
const round = value => Number(value.toFixed(3));

function lip(id, x, width, front, height, projection, material) {
  // Cross-section travels from the underside of the projecting lip to the embedded heel.
  const outline = [[front + 0.014, height - 0.034], [front - projection + 0.005, height - 0.034],
    [front - projection, height - 0.027], [front - projection, height - 0.009],
    [front - projection + 0.008, height + 0.004], [front + 0.057, height + 0.004],
    [front + 0.057, height - 0.017]];
  const points = [x, x + width].flatMap(edge => outline.map(([y, z]) => [edge, y, z].map(round).join(" ")));
  const length = outline.length;
  const triangles = [[0, 1, 6], [1, 2, 6], [2, 3, 6], [3, 4, 6], [4, 5, 6]];
  for (const [a, b, c] of [...triangles]) triangles.push([a + length, c + length, b + length]);
  for (let i = 0; i < length; i++) {
    const j = (i + 1) % length;
    triangles.push([j, i, i + length], [j, i + length, j + length]);
  }
  return `  <faceted-solid id="${id}" collidable="false" material="${material}" points="${points.join("; ")}" triangles="${triangles.map(t => t.join(" ")).join("; ")}"/>`;
}

function box(id, x, y, z, width, depth, height, material) {
  return `  <box id="${id}" position="${[x,y,z].map(round).join(" ")}" width="${round(width)}" depth="${round(depth)}" height="${round(height)}" material="${material}" collidable="false"/>`;
}

const xMin = -11.085;
const width = 2.17;
const runs = [0.528, 0.548, 0.529, 0.538];
const details = [start];
for (let step = 0; step < 6; step++) {
  const y = 6.85 + step * 2.45 / 6;
  const z = 0.33 + step * 0.15;
  const station = step + 1;
  let x = xMin;
  for (let piece = 0; piece < runs.length; piece++) {
    const run = runs[(piece + step) % runs.length];
    const projection = [0.024, 0.031, 0.026, 0.034, 0.021][(step * 3 + piece) % 5];
    const setback = piece === 2 && [1, 4].includes(step) ? 0.014 : 0;
    details.push(lip(`tread-${station}-nosing-${piece + 1}`, x, run, y + setback, z,
      projection, piece === 1 && step === 4 ? "stair-edge-repair" : "stair-edge"));
    x += run + 0.007;
  }
  for (let line = 0; line < 2; line++) {
    const broken = -10.92 + ((step * 0.21 + line * 0.31) % 0.72);
    const seamY = y + 0.078 + line * 0.023;
    details.push(box(`tread-${station}-grip-${line + 1}a`, xMin + 0.033, seamY, z + 0.001,
      broken - xMin - 0.033, 0.007, 0.001, "stair-groove"));
    details.push(box(`tread-${station}-grip-${line + 1}b`, broken + 0.023, seamY, z + 0.001,
      xMin + width - broken - 0.064, 0.007, 0.001, "stair-groove"));
  }
  const joint = -10.35 + (step % 3) * 0.28;
  details.push(box(`riser-${station}-pour-joint`, joint, y - 0.002, z - 0.124,
    0.008, 0.001, 0.088, "stair-groove"));
}

const railX = -8.9;
for (const [i, t] of [0, 1/3, 2/3, 1].entries()) {
  const y = 6.85 + t * 2.45;
  const base = i === 3 ? 1.08 : 0.33 + i * 0.30;
  details.push(box(`stair-post-${i + 1}-shoe`, railX - 0.052, y - 0.049, base + 0.001,
    0.098, 0.100, 0.019, "stair-rail-rust"));
  details.push(box(`stair-post-${i + 1}-collar`, railX - 0.031, y - 0.032, base + 0.026,
    0.062, 0.064, 0.051, "stair-rail-rust"));
  for (const [j, offset] of [-0.037, 0.031].entries())
    details.push(`  <cylinder id="stair-post-${i + 1}-bolt-${j + 1}" position="${round(railX + offset)} ${round(y + 0.034)} ${round(base + 0.02)}" radius="0.008" height="0.008" segments="6" material="stair-rail-rust" collidable="false"/>`);
}
details.push(end);

let source = await readFile(scene, "utf8");
if (source.includes(start)) {
  source = source.slice(0, source.indexOf(start)) + source.slice(source.indexOf(end) + end.length + 1);
}
const marker = '  <marker id="plaza-start"';
if (!source.includes(marker)) throw new Error("Lower stair insertion point missing");
source = source.replace(marker, details.join("\n") + "\n" + marker);
if (process.argv.includes("--update-source")) await writeFile(scene, source);

const tiled = source
  .replace('id="kowloon-circulation" name="Rain Cut · Kowloon circulation study"',
    'id="kowloon-circulation-tiled" name="Rain Cut · Tiled stair variant"')
  .replace(/(<(?:stairs|landing) id="(?:alley-lower|alley-turn)"[^\n]*?)material="stair-concrete"/g, '$1material="stair-mosaic"')
  .replace(/(<faceted-solid id="tread-[^\n]*?material=")stair-edge(")/g, '$1stair-tile-edge$2')
  .replace(marker, [
    '  <profile id="alley-tiled-entry-plan" points="-11.09 5.84; -8.91 5.84; -8.91 6.849; -11.09 6.849"/>',
    '  <slab id="alley-tiled-entry" profile="alley-tiled-entry-plan" elevation="0.186" thickness="0.004" material="stair-mosaic" collidable="false"/>',
    marker,
  ].join("\n"))
  .replace(/((?:texture|normal-texture|metallic-roughness-texture)=")(textures\/[^"]+)"/g,
    (_, opening, path) => opening + relative(dirname(destination), resolve(project, path)).replaceAll("\\", "/") + '"');
await mkdir(dirname(destination), {recursive: true});
await writeFile(destination, tiled);

